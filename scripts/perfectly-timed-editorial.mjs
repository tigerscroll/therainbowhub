export function reviewArticle(locale, value) {
  const result = structuredClone(value), copy = articleUi[locale];
  result.metadata = {title:copy.title,description:copy.description};
  Object.assign(result.landing,{title:copy.title,popupTitle:copy.popupTitle,cta:copy.cta,adNote:copy.adNote});
  result.gallery.continueLabel = copy.continueLabel;
  result.gallery.introduction = [copy.intro];
  ['cardEyebrow','cardFooter','nextLabel','finishLabel','completeEyebrow','completeTitle','completeCopy','restartLabel'].forEach((key,index) => {result.gallery[key] = copy.labels[index];});
  const titles = sectionTitles[locale]?.split('\n');
  if (titles && titles.length !== result.items.length) throw Error(`${locale}: editorial title count mismatch`);
  if (titles) result.items.forEach((item,index) => {item.title = titles[index];});
  for (const item of result.items) {
    item.paragraphs = item.paragraphs.map(text => {
      for (const [from,to] of bodyTerms[locale] ?? []) text = text.split(from).join(to);
      return text;
    });
    if (paragraphOverrides[locale]?.[item.number]) item.paragraphs = paragraphOverrides[locale][item.number];
  }
  return result;
}

